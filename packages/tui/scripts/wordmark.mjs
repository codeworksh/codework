// Generates `src/ui/glyphs.rs` from the landing site's pixel glyphs, which are the source of truth
// for the wordmark and the compact mark. The output is committed, so building the TUI never needs
// this script; run it with `--check` to fail when the glyphs have moved and the file is stale.
//
//   node scripts/wordmark.mjs           # rewrite src/ui/glyphs.rs
//   node scripts/wordmark.mjs --check   # exit 1 if it would change
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = fileURLToPath(new URL("../../../sites/www/src/components/landing/wordmark.ts", import.meta.url));
const output = fileURLToPath(new URL("../src/ui/glyphs.rs", import.meta.url));

const problems = [];
const note = (message) => problems.push(message);

const ts = readFileSync(source, "utf8");

/** The per-letter pixel grids that `compose` lays side by side. */
function letters() {
	const block = ts.slice(ts.indexOf("const LETTERS"), ts.indexOf("function compose"));
	const found = new Map();
	for (const entry of block.matchAll(/^\t([A-Z]): \[([\s\S]*?)\n\t\],/gm)) {
		found.set(
			entry[1],
			[...entry[2].matchAll(/"([#.]+)"/g)].map((row) => row[1]),
		);
	}
	if (found.size === 0) note("no letters parsed");
	return found;
}

/** `compose` from wordmark.ts, kept identical so the two agree cell for cell. */
function compose(word, glyphs) {
	const parts = word.split("").map((char) => {
		const rows = glyphs.get(char);
		if (rows === undefined) note(`no glyph for ${char}`);
		return rows;
	});
	const width = parts.reduce((sum, rows) => sum + rows[0].length + 1, 0);
	const rows = Array.from(
		{ length: parts[0].length },
		(_, row) => parts.map((letter) => letter[row].replaceAll("#", "1").replaceAll(".", "0")).join("0") + "0",
	);
	// One empty cell on the right and bottom leaves room for the outline echoes.
	return { rows: [...rows, "0".repeat(width)], width, height: parts[0].length + 1 };
}

/** A standalone `{ width, height, rows }` glyph, such as `MARK`. */
function standalone(name) {
	const at = ts.indexOf(`export const ${name}`);
	if (at < 0) {
		note(`no ${name} in wordmark.ts`);
		return undefined;
	}
	const block = ts.slice(at, ts.indexOf("};", at));
	const rows = [...block.matchAll(/"([01]+)"/g)].map((row) => row[1]);
	const width = Number(block.match(/width:\s*(\d+)/)?.[1]);
	const height = Number(block.match(/height:\s*(\d+)/)?.[1]);
	return { rows, width, height };
}

const glyphs = letters();
const wordmark = compose("CODEWORK", glyphs);
const mark = standalone("MARK");

// Both glyphs feed a cell grid, so a ragged or mistyped grid has to fail here rather than draw
// something subtly wrong.
function check(name, glyph) {
	if (glyph === undefined) return;
	if (glyph.rows.length !== glyph.height) note(`${name}: ${glyph.rows.length} rows, height says ${glyph.height}`);
	for (const [i, row] of glyph.rows.entries()) {
		if (row.length !== glyph.width) note(`${name}: row ${i} is ${row.length} wide, width says ${glyph.width}`);
		if (!/^[01]+$/.test(row)) note(`${name}: row ${i} is not binary`);
	}
}

check("CODEWORK", wordmark);
check("MARK", mark);

if (problems.length > 0) {
	console.error(`wordmark.mjs: the site's glyphs are not what this expects:\n  ${problems.join("\n  ")}`);
	process.exit(1);
}

const rows = (glyph) => glyph.rows.map((row) => `        "${row}",`).join("\n");
const glyph = (name, doc, value) =>
	`/// ${doc}\npub static ${name}: Glyph = Glyph {
    width: ${value.width},
    height: ${value.height},
    rows: &[
${rows(value)}
    ],
};`;

const header = [
	"// @generated by scripts/wordmark.mjs from the landing site's pixel glyphs. Do not edit.",
	"//",
	"// Source: sites/www/src/components/landing/wordmark.ts. Re-run `node scripts/wordmark.mjs`",
	"// after it moves; `--check` fails on drift.",
].join("\n");

const generated = `${header}

use super::wordmark::Glyph;

${glyph("WORDMARK", "CODEWORK, laid out on the site's pixel grid.", wordmark)}

${glyph("MARK", "The C-and-cursor logo, on the same grid and small enough to draw where the wordmark cannot fit.", mark)}
`;

if (process.argv.includes("--check")) {
	if (readFileSync(output, "utf8") !== generated) {
		console.error("wordmark.mjs: src/ui/glyphs.rs is stale — run `node scripts/wordmark.mjs`");
		process.exit(1);
	}
	console.log(`wordmark.mjs: the wordmark and mark are up to date`);
	process.exit(0);
}

writeFileSync(output, generated);
console.log(
	`wordmark.mjs: wrote a ${wordmark.width}x${wordmark.height} wordmark and a ${mark.width}x${mark.height} mark`,
);
